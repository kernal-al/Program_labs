#include <iostream>
int main()
{
	setlocale(LC_ALL, "RU");
	int money;
	std::cout << "Введите количество денег(с копейками): " ;
	std::cin >> money;
	// Разделяем начальную сумму на рубли и копейки
	// Например, если ввели 4647, то rubles = 46, kopecks = 47
	int rubles = money / 100;
	int kopecks = money % 100;

	// Запоминаем самый лучший результат (изначально это наши стартовые деньги)
	int max_money = money;
	int best_step = 0; // Изначально лучший шаг — 0 (никуда не ходить)

	// Переменные, которые будут меняться в цикле проходов по мосту
	int curr_rub = rubles;
	int curr_kop = kopecks;

	// Моделируем 10 000 проходов по мосту (этого точно хватит)
	for (int step = 1; step <= 10000; ++step)
	{
		// Если денег меньше, чем 29 копеек, мы не можем сделать шаг
		if (curr_rub == 0 && curr_kop < 29)
		{
			break;
		}

		// Вычитаем 29 копеек
		if (curr_kop >= 29)
		{
			curr_kop -= 29;
		}
		else
		{
			curr_rub -= 1;
			curr_kop += 71; // Заняли 1 рубль (100 копеек) и вычли 29 копеек
		}

		// Волшебство моста: меняем местами рубли и копейки
		std::swap(curr_rub, curr_kop);

		// Считаем, сколько денег получилось на этом шаге (все переводим в копейки)
		int curr_total = curr_rub * 100 + curr_kop;

		// Если текущая сумма строго больше того максимума, что мы видели раньше
		if (curr_total > max_money)
		{
			max_money = curr_total; // Обновляем максимальную сумму
			best_step = step;       // Запоминаем, на каком шаге это произошло
		}
	}

	// Выводим результат на экран
	std::cout << "Наибольшая конечная сумма: " << max_money << std::endl;
	std::cout << "Оптимальное число проходов: " << best_step << std::endl;

	return 0;

}