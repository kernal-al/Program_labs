#define _CRT_SECURE_NO_WARNINGS
#include <iostream>

int main()
{
	setlocale(LC_ALL, "RU");
	int t;
	printf("Введите сумму в копейках (46 р. 47 к. = 4647): ");
	scanf("%d", &t);

	// Для некоторых сумм проходы зацикливаются (например, с 30 копеек),
	// поэтому запоминаем уже встречавшиеся суммы. После обмена сумма < 10000,
	// так что хватает массива на 10000 флагов.
	static bool seen[10000];

	// Рубли и копейки храним отдельно: в цикле нет ни деления, ни остатка.
	int r = t / 100, k = t % 100;
	int best = t, bestStep = 0;

	for (int step = 1; r > 0 || k >= 29; ++step)   // сумма >= 29 копеек
	{
		// Отдаём 29 копеек, при нехватке разменивая рубль (100 - 29 = 71)
		if (k < 29) { --r; k += 71; }
		else k -= 29;

		// Меняем местами рубли и копейки
		int tmp = r; r = k; k = tmp;

		if (k >= 100)
		{
			// Бывает только после первого прохода, если сначала было >= 100 рублей:
			// "лишние" копейки переводим в рубли
			r += k / 100;
			k %= 100;
		}
		else
		{
			int cur = r * 100 + k;       // здесь сумма < 10000
			if (seen[cur])               // пошли по кругу — больше ничего нового не будет
				break;
			seen[cur] = true;
		}

		int cur = r * 100 + k;
		if (cur > best)                  // строго больше: при равенстве раньше лучше
		{
			best = cur;
			bestStep = step;
		}
	}

	printf("Наибольшая сумма: %d р. %02d к.\n", best / 100, best % 100);
	printf("Оптимальное число проходов: %d\n", bestStep);
	return 0;
}